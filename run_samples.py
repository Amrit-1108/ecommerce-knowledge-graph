"""Runs every question in sample_questions.txt through the full pipeline and saves the output."""
import json
import time
from fastapi.testclient import TestClient

from main import app

client = TestClient(app)

with open("sample_questions.txt", encoding="utf-8") as f:
    questions = [line.strip() for line in f if line.strip()]

lines = ["# Sample Questions and Results\n"]
for i, question in enumerate(questions, 1):
    result = client.post("/ask", json={"question": question}).json()
    print(f"{i}. {question}")
    time.sleep(10)  # stay under the free tier tokens-per-minute limit

    lines.append(f"## {i}. {question}\n")
    lines.append("**Graph query generated by LLM:**\n")
    lines.append(f"```json\n{json.dumps(result.get('graph_query'), indent=2)}\n```\n")
    lines.append(f"**Nodes retrieved:** {result.get('results_found')}\n")
    lines.append(f"**Answer:** {result.get('answer', result)}\n")

with open("sample_results.md", "w", encoding="utf-8") as f:
    f.write("\n".join(lines))

print("\nSaved to sample_results.md")
